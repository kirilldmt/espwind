from pathlib import Path
import gzip
root=Path(__file__).resolve().parents[1]
body=gzip.compress((root/'wind64/web.html').read_bytes(),mtime=0)
lines=[', '.join(str(x) for x in body[i:i+24]) for i in range(0,len(body),24)]
(root/'wind64/web_page.h').write_text('// Generated by firmware/scripts/generate-web.py\n#pragma once\n#include <stdint.h>\nstatic const uint8_t WEB_PAGE[] PROGMEM={\n'+',\n'.join(lines)+'\n};\n')
